def validate_output_directory_target(output_dir: Path) -> tuple[Path, str]:
    output_parent = output_dir.parent
    output_name = output_dir.name
    if not output_name:
        raise ValueError("comparison output directory must not be the filesystem root")

    output_parent.mkdir(parents=True, exist_ok=True)
    if output_dir.is_symlink() or (output_dir.exists() and not output_dir.is_dir()):
        raise ValueError(
            f"comparison output path must be a directory, not {output_dir}"
        )
    return output_parent, output_name


def quarantine_current_output_directory(output_dir: Path) -> Path | None:
    """Move an earlier result out of the canonical path before evaluation."""

    output_parent, output_name = validate_output_directory_target(output_dir)
    if not output_dir.exists():
        return None

    previous_dir = Path(
        tempfile.mkdtemp(prefix=f".{output_name}.previous-", dir=output_parent)
    )
    previous_dir.rmdir()
    output_dir.replace(previous_dir)
    print(
        f"Previous comparison quarantined as non-current: {previous_dir}",
        file=sys.stderr,
    )
    return previous_dir


def publish_complete_output_directory(
    output_dir: Path,
    writer: Callable[[Path], None],
    previous_dir: Path | None = None,
) -> None:
    """Stage a complete report set beside its empty canonical destination."""

    output_parent, output_name = validate_output_directory_target(output_dir)
    if output_dir.exists():
        raise RuntimeError(
            f"comparison output became current during evaluation: {output_dir}"
        )

    staging_dir = Path(
        tempfile.mkdtemp(prefix=f".{output_name}.staging-", dir=output_parent)
    )
    try:
        writer(staging_dir)
        if output_dir.exists():
            raise RuntimeError(
                f"comparison output became current during staging: {output_dir}"
            )
        staging_dir.replace(output_dir)
        if previous_dir is not None and previous_dir.exists():
            shutil.rmtree(previous_dir)
    finally:
        if staging_dir.exists():
            shutil.rmtree(staging_dir)


