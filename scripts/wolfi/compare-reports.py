def display_bytes(value: int | None) -> str:
    return "" if value is None else f"{value / (1024 * 1024):.1f} MiB"


def release_gate_markdown(release_gate: dict[str, Any]) -> str:
    status = release_gate.get("status")
    if status == "PASS":
        return (
            "**Wolfi release gate: PASS** — the evaluated acceptance result "
            "matches the verified final-image reports and contains no Critical "
            "or High findings."
        )
    if status == "FAIL":
        return (
            "**Wolfi release gate: FAIL** — "
            f"{release_gate['occurrences']['CRITICAL']} Critical and "
            f"{release_gate['occurrences']['HIGH']} High occurrences."
        )
    label = "NOT EVALUATED" if status == "NOT_EVALUATED" else "UNVERIFIED"
    return f"**Wolfi release gate: {label}** — {release_gate.get('reason', '')}"


