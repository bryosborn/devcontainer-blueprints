def main() -> None:
    args = parse_args()
    if args.skip_image_metrics and args.full_image_metrics:
        raise SystemExit("ERROR: --skip-image-metrics and --full-image-metrics conflict")
    if args.skip_image_metrics and args.require_image_metrics:
        raise SystemExit("ERROR: --skip-image-metrics and --require-image-metrics conflict")

    # A newly requested evaluation makes any previous PASS non-current before
    # report validation or the potentially long full-image metric collection.
    # Preserve it beside the canonical path for manual recovery if this run
    # fails or is interrupted; only a complete new generation becomes current.
    previous_output_dir = quarantine_current_output_directory(args.output_dir)

    lock_identity: dict[str, Any] | None = None
    if args.wolfi_lock is not None:
        lock_identity = load_wolfi_lock_identity(args.wolfi_lock)
    elif not args.allow_unverified_scan_context:
        raise SystemExit(
            "ERROR: --wolfi-lock is required for a verified release comparison"
        )

    ubuntu = load_family("ubuntu-raw", args.ubuntu_dir.resolve())
    wolfi = load_family("wolfi-raw", args.wolfi_dir.resolve())
    policy = (
        load_family("ubuntu-policy-header-packages", args.ubuntu_policy_dir.resolve())
        if args.ubuntu_policy_dir is not None
        else None
    )
    scan_context = verify_scan_context(
        ubuntu["scanMetadata"],
        wolfi["scanMetadata"],
        policy["scanMetadata"] if policy is not None else None,
        args.allow_unverified_scan_context,
    )
    if lock_identity is None:
        scan_context["verified"] = False
        scan_context["reason"] = (
            "No current Wolfi lock was supplied; report and final-image identity "
            "cannot be verified."
        )

    suite: dict[str, Any] | None = None
    if args.suite_metadata is not None:
        if not args.suite_metadata.is_file():
            if not args.allow_unverified_scan_context:
                raise SystemExit(
                    f"ERROR: Scan-suite provenance not found: {args.suite_metadata}"
                )
        else:
            suite = read_json(args.suite_metadata.resolve())
            if suite.get("scannerContextFrozen") is not True:
                raise SystemExit("ERROR: Scan suite does not claim a frozen context")
            if suite.get("platform") != scan_context.get("scannerOptions", {}).get(
                "platform"
            ):
                raise SystemExit("ERROR: Scan-suite platform differs from raw metadata")
            suite_trivy = suite.get("trivy") or {}
            raw_trivy = (ubuntu["scanMetadata"] or {}).get("trivy") or {}
            if suite_trivy.get("Version") != raw_trivy.get("Version"):
                raise SystemExit("ERROR: Scan-suite Trivy version differs from raw metadata")
            for database_key in ("VulnerabilityDB", "JavaDB"):
                suite_database = suite_trivy.get(database_key) or {}
                raw_database = raw_trivy.get(database_key) or {}
                if (
                    suite_database.get("Version") != raw_database.get("Version")
                    or suite_database.get("UpdatedAt") != raw_database.get("UpdatedAt")
                ):
                    raise SystemExit(
                        f"ERROR: Scan-suite {database_key} snapshot differs from raw metadata"
                    )
            expected_ubuntu_images = ((suite.get("ubuntu") or {}).get("images")) or []
            expected_wolfi_images = ((suite.get("wolfi") or {}).get("images")) or []
            actual_ubuntu_images = (ubuntu["scanMetadata"] or {}).get("images") or []
            actual_wolfi_images = (wolfi["scanMetadata"] or {}).get("images") or []
            if expected_ubuntu_images != actual_ubuntu_images:
                raise SystemExit("ERROR: Scan-suite Ubuntu image manifest differs")
            if expected_wolfi_images != actual_wolfi_images:
                raise SystemExit("ERROR: Scan-suite Wolfi image manifest differs")
            wolfi_suite = suite.get("wolfi")
            ubuntu_suite = suite.get("ubuntu")
            if not isinstance(wolfi_suite, dict) or not isinstance(ubuntu_suite, dict):
                raise SystemExit("ERROR: Scan suite has invalid family metadata")
            if lock_identity is not None:
                if wolfi_suite.get("lockSha256") != lock_identity["sha256"]:
                    raise SystemExit(
                        "ERROR: Scan suite was not produced from the current exact "
                        "Wolfi lock bytes"
                    )
                if suite.get("platform") != lock_identity["platform"]:
                    raise SystemExit(
                        "ERROR: Scan-suite platform differs from the current Wolfi lock"
                    )
            if ubuntu_suite.get("enabled") is not True:
                raise SystemExit("ERROR: Scan suite does not contain an Ubuntu baseline")
            if wolfi_suite.get("ignorePolicyApplied") is not False:
                raise SystemExit("ERROR: Scan suite does not describe raw Wolfi findings")
            final_images = wolfi_suite.get("finalImages")
            if (
                not isinstance(final_images, list)
                or len(final_images) != 3
                or any(image not in expected_wolfi_images for image in final_images)
                or len(set(final_images)) != len(final_images)
            ):
                raise SystemExit("ERROR: Scan-suite final Wolfi image manifest is invalid")
            if lock_identity is not None and final_images != lock_identity["finalImages"]:
                raise SystemExit(
                    "ERROR: Scan-suite final Wolfi image manifest differs from the "
                    "current lock"
                )
            wolfi_boundaries = wolfi_suite.get("boundaries")
            if not isinstance(wolfi_boundaries, dict) or [
                wolfi_boundaries.get(key) for key in ("dod", "vscode", "toolchain")
            ] != final_images:
                raise SystemExit("ERROR: Scan-suite Wolfi boundaries are invalid")
            native_tool_probe_assessment_complete = (
                validate_native_tool_probe_assessment(
                    wolfi_suite, expected_wolfi_images, lock_identity
                )
            )
            ubuntu_boundaries = ubuntu_suite.get("boundaries")
            if not isinstance(ubuntu_boundaries, dict) or any(
                ubuntu_boundaries.get(key) not in expected_ubuntu_images
                for key in ("dod", "vscode")
            ):
                raise SystemExit("ERROR: Scan-suite Ubuntu boundaries are invalid")
            all_tools = ubuntu_suite.get("allToolsComparison")
            if not isinstance(all_tools, dict):
                raise SystemExit("ERROR: Scan suite lacks all-tools comparison metadata")
            if all_tools.get("equivalent") is True:
                comparator_provenance = all_tools.get("provenance")
                if (
                    not native_tool_probe_assessment_complete
                    or all_tools.get("status") != "included"
                    or all_tools.get("image") not in expected_ubuntu_images
                    or not isinstance(comparator_provenance, dict)
                    or comparator_provenance.get("validated") is not True
                    or comparator_provenance.get("scanIdentityValidated") is not True
                ):
                    raise SystemExit(
                        "ERROR: Scan-suite all-tools equivalence is not substantiated"
                    )
            include_vsix = suite.get("includeVsixArchive")
            if not isinstance(include_vsix, bool):
                raise SystemExit("ERROR: Scan suite has an invalid VSIX inclusion setting")
            raw_skip_files = scan_context.get("scannerOptions", {}).get("skipFiles") or []
            vsix_was_excluded = (
                "/home/vscode/vscode-extensions.tar.gz" in raw_skip_files
            )
            if include_vsix == vsix_was_excluded:
                raise SystemExit(
                    "ERROR: Scan-suite VSIX setting differs from raw scanner options"
                )
    elif not args.allow_unverified_scan_context:
        raise SystemExit(
            "ERROR: --suite-metadata is required for an equivalence comparison"
        )

    acceptance_path = (
        args.acceptance_file.resolve() if args.acceptance_file is not None else None
    )
    acceptance: dict[str, Any] | None = None
    if acceptance_path is None:
        if not args.allow_unverified_scan_context:
            raise SystemExit(
                "ERROR: --acceptance-file is required for a release comparison"
            )
    elif acceptance_path.is_file():
        acceptance = read_json(acceptance_path)
    elif not args.allow_unverified_scan_context:
        raise SystemExit(f"ERROR: Wolfi acceptance result not found: {acceptance_path}")
    release_gate = build_release_gate(
        wolfi, suite, scan_context, acceptance, acceptance_path
    )

    native_tool_versions = None
    if args.native_tool_version_report is not None:
        if args.native_tool_version_report.is_file():
            native_tool_versions = read_json(args.native_tool_version_report.resolve())
            if native_tool_versions.get("nativeTool") != "mongosh":
                raise SystemExit("ERROR: Native-tool version report is not for mongosh")
            enabled = native_tool_versions.get("enabled")
            discrepancy = native_tool_versions.get(
                "packageRuntimeVersionDiscrepancy"
            )
            if not isinstance(enabled, bool) or not isinstance(discrepancy, bool):
                raise SystemExit("ERROR: Native-tool version report has invalid booleans")
            if enabled and (
                not isinstance(native_tool_versions.get("apkVersion"), str)
                or not native_tool_versions.get("apkVersion")
                or not isinstance(native_tool_versions.get("runtimeVersion"), str)
                or not native_tool_versions.get("runtimeVersion")
            ):
                raise SystemExit("ERROR: Native-tool version report lacks versions")
            if suite is not None:
                expected_toolchain = str(
                    (((suite.get("wolfi") or {}).get("boundaries") or {}).get("toolchain"))
                    or ""
                )
                if native_tool_versions.get("image") != expected_toolchain:
                    raise SystemExit(
                        "ERROR: Native-tool version report is for a different image"
                    )
        elif not args.allow_unverified_scan_context:
            raise SystemExit(
                "ERROR: Native-tool version report not found: "
                f"{args.native_tool_version_report}"
            )

    families = [ubuntu, wolfi] + ([policy] if policy is not None else [])
    docker_available = shutil.which("docker") is not None
    metric_cache: dict[str, dict[str, Any]] = {}
    for family in families:
        for image in family["images"]:
            if args.skip_image_metrics:
                metrics = unavailable_metrics("image metrics skipped")
            elif not docker_available:
                metrics = unavailable_metrics("docker command not found")
            elif image["name"] in metric_cache:
                metrics = metric_cache[image["name"]]
            else:
                metrics = collect_image_metrics(image["name"], args.full_image_metrics)
                metric_cache[image["name"]] = metrics
            image["imageMetrics"] = metrics
            scanned_identity = image.get("scannedImageIdentity") or {}
            if metrics["available"] and scanned_identity:
                if metrics["imageId"] != scanned_identity.get("imageId"):
                    raise SystemExit(
                        f"ERROR: Docker tag changed since scan: {image['name']}"
                    )
                if metrics["platform"] != scanned_identity.get("platform"):
                    raise SystemExit(
                        f"ERROR: Docker image platform changed since scan: {image['name']}"
                    )
            if args.require_image_metrics:
                required_metrics = [
                    "imageSizeBytes",
                    "layerCount",
                    "installedPackageCount",
                ]
                if args.full_image_metrics:
                    required_metrics.extend(
                        (
                            "compressedSaveBytes",
                            "compressedExportBytes",
                            "liveFilesystemBytes",
                        )
                    )
                missing_metrics = [
                    key for key in required_metrics if metrics.get(key) is None
                ]
                if not metrics["available"] or missing_metrics or metrics["errors"]:
                    errors = "; ".join(metrics["errors"])
                    detail = ", ".join(missing_metrics) or "image inspection"
                    if metrics["errors"] and not missing_metrics:
                        detail = "one or more metric collectors"
                    raise SystemExit(
                        f"ERROR: Required Docker metrics unavailable for "
                        f"{image['name']} ({detail}): {errors}"
                    )

    probe_contributions = build_probe_contributions(wolfi, suite)
    boundary_comparisons = build_boundary_comparisons(ubuntu, wolfi, suite)

    generated_at = (
        datetime.now(timezone.utc)
        .replace(microsecond=0)
        .isoformat()
        .replace("+00:00", "Z")
    )
    output = {
        "schemaVersion": 2,
        "generatedAt": generated_at,
        "fullImageMetrics": args.full_image_metrics,
        "scanContext": scan_context,
        "scanSuite": suite,
        "boundaryComparisons": boundary_comparisons,
        "probeContributions": probe_contributions,
        "releaseGate": release_gate,
        "nativeToolVersions": native_tool_versions,
        "families": strip_internal_values(families),
    }

    def write_output_set(staging_dir: Path) -> None:
        (staging_dir / "comparison.json").write_text(
            json.dumps(output, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        write_vulnerability_tsv(
            staging_dir / "vulnerability-comparison.tsv", families
        )
        write_native_tool_tsv(
            staging_dir / "native-tool-contributions.tsv", families
        )
        write_package_contributions_tsv(
            staging_dir / "package-contributions.tsv", families
        )
        write_vulnerability_layer_tsv(
            staging_dir / "vulnerability-layer-contributions.tsv", families
        )
        write_remaining_wolfi_tsv(
            staging_dir / "remaining-wolfi-findings.tsv", wolfi
        )
        write_image_metrics_tsv(staging_dir / "image-metrics.tsv", families)
        write_layer_contributions_tsv(
            staging_dir / "image-layer-contributions.tsv", families
        )
        write_probe_contributions_tsv(
            staging_dir / "native-tool-probe-contributions.tsv", probe_contributions
        )
        write_boundary_comparison_tsv(
            staging_dir / "equivalent-boundary-comparison.tsv", boundary_comparisons
        )
        write_markdown(
            staging_dir / "comparison.md",
            families,
            args.full_image_metrics,
            scan_context,
            boundary_comparisons,
            probe_contributions,
            native_tool_versions,
            release_gate,
        )

    publish_complete_output_directory(
        args.output_dir, write_output_set, previous_output_dir
    )
    print(f"Wolfi/Ubuntu comparison written to {args.output_dir}")


if __name__ == "__main__":
    main()
